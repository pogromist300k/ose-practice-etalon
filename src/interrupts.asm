  push DS
  push ES
  push FS
  push GS
  pusha

  cld
  mov AX, DATA_SELECTOR
  mov DS, AX
  mov ES, AX
  mov FS, AX
  mov GS, AX

  mov EBX, ESP
  sub ESP, 4
  and ESP, -16
  mov dword[ESP], EBX

  [EXTERN interrupt_handler]
  ; void interrupt_handler(Context* ctx)
  call interrupt_handler

  mov ESP, EBX
  popa
  pop GS
  pop FS
  pop ES
  pop DS
  add ESP, 8
  iret

